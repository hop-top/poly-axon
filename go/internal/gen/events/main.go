// Command gen-events writes events_gen.go from spec/events.yaml.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"

	"gopkg.in/yaml.v3"

	"hop.top/axon/internal/gen/ident"
)

func main() {
	in := flag.String("in", "spec/events.yaml", "catalog path")
	out := flag.String("out", "events_gen.go", "output path")
	check := flag.Bool("check", false, "exit 1 if output differs from disk")
	flag.Parse()

	raw, err := os.ReadFile(*in)
	if err != nil {
		fatal(err)
	}
	var doc struct {
		Events []struct {
			Name        string `yaml:"name"`
			Description string `yaml:"description"`
		} `yaml:"events"`
	}
	if err := yaml.Unmarshal(raw, &doc); err != nil {
		fatal(err)
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by internal/gen/events from spec/events.yaml; DO NOT EDIT.\n\npackage axon\n\nconst (\n")
	for _, e := range doc.Events {
		fmt.Fprintf(&b, "\t// Event%s: %s\n\tEvent%s Event = %q\n", ident.Export(e.Name), e.Description, ident.Export(e.Name), e.Name)
	}
	fmt.Fprintf(&b, ")\n\n// allEventConstants lists every generated constant, in catalog order.\nvar allEventConstants = []Event{\n")
	for _, e := range doc.Events {
		fmt.Fprintf(&b, "\tEvent%s,\n", ident.Export(e.Name))
	}
	fmt.Fprintf(&b, "}\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		fatal(err)
	}
	if *check {
		cur, _ := os.ReadFile(*out)
		if !bytes.Equal(cur, src) {
			fmt.Fprintln(os.Stderr, "events_gen.go is stale; run go generate ./...")
			os.Exit(1)
		}
		return
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil { //nolint:gosec // generated Go source, meant to be world-readable like any other checked-in file
		fatal(err)
	}
}

func fatal(err error) { fmt.Fprintln(os.Stderr, "gen-events:", err); os.Exit(1) }
