// Command gen-hosts writes hosts_gen.go from the spec/hosts directories.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"

	"hop.top/axon/internal/gen/ident"
)

func main() {
	in := flag.String("in", "spec/hosts", "hosts directory")
	out := flag.String("out", "hosts_gen.go", "output path")
	check := flag.Bool("check", false, "exit 1 if output differs from disk")
	flag.Parse()

	entries, err := os.ReadDir(*in)
	if err != nil {
		fatal(err)
	}
	var names []string
	for _, e := range entries {
		if e.IsDir() {
			names = append(names, e.Name())
		}
	}
	sort.Strings(names)

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by internal/gen/hosts from spec/hosts; DO NOT EDIT.\n\npackage axon\n\nconst (\n")
	for _, n := range names {
		fmt.Fprintf(&b, "\tHost%s = %q\n", ident.Export(n), n)
	}
	fmt.Fprintf(&b, ")\n\n// allHostNames lists every generated host directory name, sorted.\nvar allHostNames = []string{\n")
	for _, n := range names {
		fmt.Fprintf(&b, "\t%q,\n", n)
	}
	fmt.Fprintf(&b, "}\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		fatal(err)
	}
	if *check {
		cur, _ := os.ReadFile(*out)
		if !bytes.Equal(cur, src) {
			fmt.Fprintln(os.Stderr, filepath.Base(*out)+" is stale; run go generate ./...")
			os.Exit(1)
		}
		return
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil { //nolint:gosec // generated Go source, meant to be world-readable like any other checked-in file
		fatal(err)
	}
}

func fatal(err error) { fmt.Fprintln(os.Stderr, "gen-hosts:", err); os.Exit(1) }
